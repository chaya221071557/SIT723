def binary_scores(actual: np.ndarray, predicted: np.ndarray) -> dict[str, float]:
    actual = np.asarray(actual, dtype=int)
    predicted = np.asarray(predicted, dtype=int)
    prevalence = float(actual.mean())
    if len(np.unique(actual)) == 2:
        balanced = float(balanced_accuracy_score(actual, predicted))
    else:
        balanced = float("nan")
    return {
        "prevalence": prevalence,
        "predicted_prevalence": float(predicted.mean()),
        "accuracy": float(accuracy_score(actual, predicted)),
        "balanced_accuracy": balanced,
        "precision": float(precision_score(actual, predicted, zero_division=0)),
        "recall": float(recall_score(actual, predicted, zero_division=0)),
        "F1": float(f1_score(actual, predicted, zero_division=0)),
    }


def select_candidate(
    name: str,
    candidates: Iterable[float],
    actual_measure: np.ndarray,
    predicted_measure: np.ndarray,
    comparison: str = "ge",
) -> tuple[float, pd.DataFrame]:
    rows = []
    for threshold in candidates:
        if comparison == "ge":
            actual = actual_measure >= threshold
            predicted = predicted_measure >= threshold
        elif comparison == "gt":
            actual = actual_measure > threshold
            predicted = predicted_measure > threshold
        else:
            raise ValueError(f"Unsupported comparison: {comparison}")
        row = {"parameter": name, "candidate": float(threshold)}
        row.update(binary_scores(actual, predicted))
        rows.append(row)

    table = pd.DataFrame(rows)
    eligible = table[
        table["prevalence"].between(0.05, 0.95)
        & table["balanced_accuracy"].notna()
    ]
    if eligible.empty:
        eligible = table[table["balanced_accuracy"].notna()]
    if eligible.empty:
        raise ValueError(f"No valid validation candidate for {name}")

    selected_row = eligible.sort_values(
        ["balanced_accuracy", "F1", "candidate"],
        ascending=[False, False, True],
    ).iloc[0]
    return float(selected_row["candidate"]), table


