def probability_to_angle(probability: float) -> float:
    probability = float(np.clip(probability, 1e-8, 1.0 - 1e-8))
    return float(2.0 * np.arcsin(np.sqrt(probability)))


def build_qbi_circuit(state_name: str) -> QuantumCircuit:
    state_register = QuantumRegister(1, name=state_name)
    evidence_registers = [
        QuantumRegister(1, name=name) for name in EVIDENCE_NAMES
    ]
    circuit = QuantumCircuit(
        state_register, *evidence_registers, name=f"{state_name}_QBI"
    )
    state_qubit = state_register[0]
    circuit.ry(
        probability_to_angle(initial_priors[state_name]), state_qubit
    )
    for register, evidence_name in zip(evidence_registers, EVIDENCE_NAMES):
        circuit.ry(
            probability_to_angle(
                evidence_likelihoods[state_name][(evidence_name, 0)]
            ),
            register[0],
        )
    for register, evidence_name in zip(evidence_registers, EVIDENCE_NAMES):
        p0 = evidence_likelihoods[state_name][(evidence_name, 0)]
        p1 = evidence_likelihoods[state_name][(evidence_name, 1)]
        circuit.cry(
            probability_to_angle(p1) - probability_to_angle(p0),
            state_qubit,
            register[0],
        )
    return circuit


sampler = StatevectorSampler(default_shots=QBI_SHOTS, seed=SEED)
qbi_circuits = {
    state: build_qbi_circuit(state) for state in STATE_NAMES
}


def qiskit_posterior(
    state_name: str,
    evidence_pattern: np.ndarray,
) -> tuple[float, bool]:
    model_qbi = QBayesian(
        circuit=qbi_circuits[state_name], sampler=sampler
    )
    model_qbi.threshold = QBI_EVIDENCE_THRESHOLD
    evidence = {
        name: int(value)
        for name, value in zip(EVIDENCE_NAMES, evidence_pattern)
    }
    posterior = float(
        model_qbi.inference(query={state_name: 1}, evidence=evidence)
    )
    return posterior, bool(model_qbi.converged)


