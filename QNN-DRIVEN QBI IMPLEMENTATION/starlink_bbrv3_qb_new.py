def causal_rolling_rtt_base(
    current_values: np.ndarray,
    metadata: pd.DataFrame,
) -> np.ndarray:
    """Calculate a causal rolling Q0.05 RTT floor without future values."""
    frame = metadata.reset_index(drop=True).copy()
    frame["_original_index"] = np.arange(len(frame))
    frame["_current_rtt"] = current_values[:, 1]

    group_columns = [
        column
        for column in ("city", "run_number", "json_object_number")
        if column in frame.columns
    ]
    sort_columns = group_columns + [
        column
        for column in ("target_interval", "target_end_time_s")
        if column in frame.columns
    ]
    frame = frame.sort_values(sort_columns)

    bases = np.empty(len(frame), dtype=float)
    global_floor = float(np.quantile(train_current[:, 1], 0.05))

    grouped = frame.groupby(group_columns, sort=False) if group_columns else [(None, frame)]
    for _, group in grouped:
        rolling_floor = (
            group["_current_rtt"]
            .rolling(
                window=ROLLING_RTT_WINDOW,
                min_periods=MIN_RTT_HISTORY,
            )
            .quantile(0.05)
        )
        expanding_floor = group["_current_rtt"].expanding().quantile(0.05)
        floor = rolling_floor.fillna(expanding_floor).fillna(global_floor)
        bases[group["_original_index"].to_numpy(int)] = floor.to_numpy(float)
    return bases


