def exact_posterior(
    state_name: str,
    evidence_pattern: np.ndarray,
) -> float:
    prior = initial_priors[state_name]
    numerator = prior
    alternative = 1.0 - prior
    for value, evidence_name in zip(evidence_pattern, EVIDENCE_NAMES):
        p1 = evidence_likelihoods[state_name][(evidence_name, 1)]
        p0 = evidence_likelihoods[state_name][(evidence_name, 0)]
        numerator *= p1 if value else 1.0 - p1
        alternative *= p0 if value else 1.0 - p0
    denominator = numerator + alternative
    return float(numerator / denominator) if denominator else prior


