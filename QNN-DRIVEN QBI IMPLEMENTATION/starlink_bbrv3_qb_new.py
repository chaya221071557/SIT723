def create_evidence(
    current_values: np.ndarray,
    next_values: np.ndarray,
    queue_delay: np.ndarray,
) -> np.ndarray:
    drop = (
        (current_values[:, 0] - next_values[:, 0])
        / np.maximum(current_values[:, 0], 1e-6)
    )
    return np.column_stack([
        (drop >= THRESHOLDS["throughput_drop_ratio"])
        | (next_values[:, 0] <= THRESHOLDS["absolute_low_throughput"]),
        queue_delay > THRESHOLDS["high_queue_delay"],
        next_values[:, 2] >= THRESHOLDS["high_rtt_variance"],
        next_values[:, 3] >= THRESHOLDS["retransmission_burst"],
    ]).astype(np.int8)


def create_proxy_states(
    current_values: np.ndarray,
    next_values: np.ndarray,
    evidence: np.ndarray,
) -> np.ndarray:
    drop = (
        (current_values[:, 0] - next_values[:, 0])
        / np.maximum(current_values[:, 0], 1e-6)
    )
    low, queue, variance, retransmission = evidence.T.astype(bool)
    queue_build_up = queue
    congestion = queue & (low | retransmission)
    disruption = (
        (drop >= THRESHOLDS["severe_throughput_drop_ratio"])
        | (next_values[:, 0] <= THRESHOLDS["absolute_low_throughput"])
    ) & variance
    return np.column_stack([
        congestion, queue_build_up, disruption
    ]).astype(np.int8)


