def temporal_compression(X: np.ndarray) -> np.ndarray:
    if X.ndim != 3:
        raise ValueError(f"Expected a 3-D sequence array, received {X.shape}.")

    window_mean = X.mean(axis=1)
    latest_value = X[:, -1, :]
    trend = X[:, -1, :] - X[:, 0, :]
    compressed = np.concatenate([window_mean, latest_value, trend], axis=1)
    angles = np.pi * np.tanh(compressed / 3.0)
    return angles.astype(np.float32)


