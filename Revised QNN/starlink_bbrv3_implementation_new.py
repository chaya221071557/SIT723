def create_run_sequences(run_df: pd.DataFrame, window_size: int, input_features: list[str], target_features: list[str]):
    run_df = (run_df.sort_values("interval_number").reset_index(drop=True))

    input_values = run_df[input_features].to_numpy(dtype=np.float32)

    target_values = run_df[target_features].to_numpy(dtype=np.float32)

    X_samples = []
    y_samples = []
    metadata = []

    number_of_intervals = len(run_df)

    if number_of_intervals <= window_size:
        return (np.empty((0, window_size, len(input_features)), dtype=np.float32), np.empty((0, len(target_features)), dtype=np.float32), [])

    for start_index in range(number_of_intervals - window_size):
        end_index = start_index + window_size
        target_index = end_index

        X_window = input_values[start_index:end_index]
        y_target = target_values[target_index]

        X_samples.append(X_window)
        y_samples.append(y_target)

        metadata.append({"city": run_df.loc[0, "city"], "run_number": int(run_df.loc[0, "run_number"]), "run_id": run_df.loc[0, "run_id"],
            "json_object_number": int(run_df.loc[0, "json_object_number"]),
            "window_start_interval": int(
                run_df.loc[start_index, "interval_number"]),
            "window_end_interval": int(run_df.loc[end_index - 1, "interval_number"]),
            "target_interval": int(
                run_df.loc[target_index, "interval_number"]),
            "target_end_time_s": float(run_df.loc[target_index, "end_time_s"])
        })

    return (np.asarray(X_samples, dtype=np.float32),np.asarray(y_samples, dtype=np.float32), metadata)

