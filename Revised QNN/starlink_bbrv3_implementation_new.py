def build_estimator_qnn(num_qubits: int = 6, num_encoding_blocks: int = 3,) -> tuple[EstimatorQNN, QuantumCircuit]:

    num_inputs = num_qubits * num_encoding_blocks
    num_weights = num_encoding_blocks * num_qubits * 2

    input_params = ParameterVector("x", num_inputs)
    weight_params = ParameterVector("theta", num_weights)
    circuit = QuantumCircuit(num_qubits, name="Starlink_QNN")

    w = 0
    for block in range(num_encoding_blocks):
        offset = block * num_qubits
        for qubit in range(num_qubits):
            circuit.ry(input_params[offset + qubit], qubit)
        for qubit in range(num_qubits):
            circuit.ry(weight_params[w], qubit)
            circuit.rz(weight_params[w + 1], qubit)
            w += 2
        for qubit in range(num_qubits - 1):
            circuit.cx(qubit, qubit + 1)
        circuit.cx(num_qubits - 1, 0)
        circuit.barrier()
    observables = []
    for measured_qubit in range(4):
        pauli = ["I"] * num_qubits
        pauli[num_qubits - 1 - measured_qubit] = "Z"
        observables.append(SparsePauliOp.from_list([("".join(pauli), 1.0)]))

    estimator = StatevectorEstimator(seed=SEED)
    qnn = EstimatorQNN(
        circuit=circuit,
        estimator=estimator,
        observables=observables,
        input_params=list(input_params),
        weight_params=list(weight_params),
        input_gradients=True,
    )
    return qnn, circuit

class HybridQNNRegressor(nn.Module):
    def __init__(self, qnn: EstimatorQNN):
        super().__init__()
        initial_weights = 0.1 * np.random.default_rng(SEED).standard_normal(qnn.num_weights)
        self.quantum_layer = TorchConnector(qnn, initial_weights=initial_weights)
        self.readout = nn.Linear(4, 4)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        quantum_values = self.quantum_layer(x)
        return self.readout(quantum_values.float())


